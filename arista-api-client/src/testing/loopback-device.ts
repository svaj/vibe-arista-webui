/**
 * In-process loopback eAPI listeners for the transport tests — M2 (#4).
 *
 * Everything here binds **127.0.0.1 on an ephemeral port** (port `0`, never a fixed number) or a unix
 * socket inside a temp directory, and every handle is returned with a `close()` the test calls in
 * `afterEach`. Nothing here can reach a switch: `host` is a literal, and the tests never send a real
 * credential anywhere (docs/TESTING.md §1, safety rules of #4).
 *
 * The certificates are the synthetic fixtures in `test/fixtures/tls/` — self-signed, loopback SANs
 * only, 100-year validity so the suite cannot rot, and regenerated by the command in that directory's
 * README. They are **not** device material: no EOS key ever appears in this repository.
 *
 * Node-only by construction (`node:http`/`node:https`/`node:fs`/`node:crypto`). It lives in
 * `src/testing/` because it is a test helper, is excluded from coverage, and is reachable from neither
 * entry point — `src/browser-safety.test.ts` proves the browser graph stays clean.
 */

import { readFileSync, unlinkSync } from 'node:fs'
import { createServer as createHttpServer, type IncomingHttpHeaders, type Server } from 'node:http'
import { createServer as createHttpsServer } from 'node:https'
import { createHash } from 'node:crypto'
import type { PeerCertificate, TLSSocket } from 'node:tls'

/** Absolute path to `test/fixtures/tls/`, resolved from this module. */
export const TLS_FIXTURE_DIR = new URL('../../test/fixtures/tls/', import.meta.url)

export function tlsFixturePath(name: 'loopback-self-signed.crt' | 'loopback-self-signed.key' | 'loopback-client.crt' | 'loopback-client.key'): string {
  return new URL(name, TLS_FIXTURE_DIR).pathname
}

export function tlsFixture(name: 'loopback-self-signed.crt' | 'loopback-self-signed.key' | 'loopback-client.crt' | 'loopback-client.key'): string {
  return readFileSync(tlsFixturePath(name), 'utf8')
}

/**
 * OpenSSL-style fingerprint of a PEM certificate (`AB:CD:…`), computed rather than hard-coded so the
 * tests keep passing when a fixture is regenerated from the documented command.
 */
export function certificateFingerprint(pem: string, algorithm: 'sha256' | 'sha1' = 'sha256'): string {
  const der = Buffer.from(pem.replace(/-----[^-]+-----/gu, '').replace(/\s/gu, ''), 'base64')
  const hex = createHash(algorithm).update(der).digest('hex').toUpperCase()
  return hex.match(/.{2}/gu)!.join(':')
}

/** A request the fake listener received, with the body already decoded — the assertion surface. */
export interface LoopbackRequest {
  readonly method: string
  readonly url: string
  readonly headers: IncomingHttpHeaders
  readonly body: string
  /** Present when the listener was configured to ask for (and receive) a client certificate. */
  readonly clientCertSubject?: Record<string, string>
}

export interface LoopbackAnswer {
  readonly status?: number
  readonly statusText?: string
  /** A header name may repeat; `Set-Cookie` in particular must be able to (DR-018). */
  readonly headers?: Readonly<Record<string, string | readonly string[]>>
  readonly body?: string
  /**
   * Drop the socket without answering — what a half-open listener or an intermediary timing out looks
   * like. The client must map it to `TransportError` with a `retryable` hint, not to a parse failure.
   */
  readonly hangUp?: boolean
  /**
   * Hold the request open this long before answering. Used to cross the client deadline, where the
   * only acceptable outcome is `TimeoutError` — not `ProtocolError` from an empty body (DR-019).
   */
  readonly delayMs?: number
}

/** Responder: sees the request plus how many times this listener has been called, and answers it. */
export type LoopbackResponder = (request: LoopbackRequest, callIndex: number) => LoopbackAnswer

export interface LoopbackDevice {
  readonly scheme: 'http' | 'https'
  readonly host: string
  readonly port: number
  /** `http://127.0.0.1:41234` — never a name that could resolve elsewhere. */
  readonly origin: string
  /** Requests received so far, in order. */
  requests(): readonly LoopbackRequest[]
  /** How many requests arrived — the assertion for "exactly one retry", "login happened once", etc. */
  callCount(): number
  /** Last request, or `undefined` when nothing arrived yet. */
  last(): LoopbackRequest | undefined
  close(): Promise<void>
}

function normalizeHeaders(headers: Readonly<Record<string, string | readonly string[]>> | undefined): Record<string, string | string[]> {
  const out: Record<string, string | string[]> = {}
  for (const [name, value] of Object.entries(headers ?? {})) {
    // `Array.isArray` does not narrow the negative half of `string | readonly string[]`, so both
    // branches are written explicitly rather than relying on inference.
    if (Array.isArray(value)) out[name] = [...(value as readonly string[])]
    else out[name] = value as string
  }
  return out
}

/** `getPeerCertificate` exists only on a TLS socket; a plain http listener hands us a `net.Socket`. */
function peerCertificate(socket: NodeJS.Socket): PeerCertificate | undefined {
  const tlsSocket = socket as Partial<TLSSocket>
  return typeof tlsSocket.getPeerCertificate === 'function' ? tlsSocket.getPeerCertificate() : undefined
}

function handleRequest(server: Server, responder: LoopbackResponder, requests: LoopbackRequest[], requireClientCert: boolean): void {
  server.on('request', (req, res) => {
    const chunks: Buffer[] = []
    req.on('data', (chunk: Buffer) => chunks.push(chunk))
    req.on('end', () => {
      // A TLS peer that presented no certificate yields an empty object, not `undefined`, so the
      // presence test is the subject rather than the object itself.
      const peer = peerCertificate(req.socket)
      const subject = peer?.subject
      const presentedClientCert = subject !== undefined && Object.keys(subject).length > 0
      const entry: LoopbackRequest = {
        method: req.method ?? '',
        url: req.url ?? '',
        headers: req.headers,
        body: Buffer.concat(chunks).toString('utf8'),
        ...(presentedClientCert ? { clientCertSubject: subject as Record<string, string> } : {}),
      }
      requests.push(entry)
      if (requireClientCert && !presentedClientCert) {
        res.writeHead(401, { 'content-type': 'text/html' })
        res.end('<html>login required</html>')
        return
      }
      const answer = responder(entry, requests.length - 1)
      if (answer.hangUp === true) {
        req.destroy()
        return
      }
      const send = (): void => {
        res.writeHead(answer.status ?? 200, answer.statusText ?? '', normalizeHeaders(answer.headers))
        res.end(answer.body ?? '')
      }
      if (answer.delayMs !== undefined) setTimeout(send, answer.delayMs).unref?.()
      else send()
    })
  })
}

function track(server: Server, responder: LoopbackResponder, requireClientCert = false): { requests: LoopbackRequest[]; listen(port: number): Promise<number> } {
  const requests: LoopbackRequest[] = []
  handleRequest(server, responder, requests, requireClientCert)
  return {
    requests,
    listen(port: number): Promise<number> {
      return new Promise((resolve, reject) => {
        server.once('error', reject)
        server.listen(port, '127.0.0.1', () => {
          const address = server.address()
          if (address === null || typeof address === 'string') reject(new Error('loopback listener did not report a port'))
          else resolve(address.port)
        })
      })
    },
  }
}

/** Cleartext loopback listener on an ephemeral port — pyeapi's `http` / `http_local` shape. */
export async function listenHttp(responder: LoopbackResponder): Promise<LoopbackDevice> {
  const server = createHttpServer()
  const tracked = track(server, responder)
  const port = await tracked.listen(0)
  return {
    scheme: 'http',
    host: '127.0.0.1',
    port,
    origin: `http://127.0.0.1:${String(port)}`,
    requests: () => tracked.requests,
    callCount: () => tracked.requests.length,
    last: () => tracked.requests.at(-1),
    close(): Promise<void> {
      return new Promise((resolve) => {
        server.closeAllConnections()
        server.close(() => resolve())
      })
    },
  }
}

/**
 * TLS loopback listener using the synthetic self-signed fixture, whose SANs are `localhost` +
 * `127.0.0.1`. `mutual` makes the server request **and verify** a client certificate against
 * `loopback-client.crt`, which is what proves the `https-client-cert` transport really presents one.
 */
export async function listenHttps(responder: LoopbackResponder, options: { readonly mutual?: boolean } = {}): Promise<LoopbackDevice> {
  const tls: Record<string, unknown> = { key: tlsFixture('loopback-self-signed.key'), cert: tlsFixture('loopback-self-signed.crt') }
  if (options.mutual === true) {
    tls.ca = [tlsFixture('loopback-client.crt')]
    tls.requestCert = true
    tls.rejectUnauthorized = true
  }
  const server = createHttpsServer(tls as never)
  const tracked = track(server, responder, options.mutual === true)
  const port = await tracked.listen(0)
  return {
    scheme: 'https',
    host: '127.0.0.1',
    port,
    origin: `https://127.0.0.1:${String(port)}`,
    requests: () => tracked.requests,
    callCount: () => tracked.requests.length,
    last: () => tracked.requests.at(-1),
    close(): Promise<void> {
      return new Promise((resolve) => {
        server.closeAllConnections()
        server.close(() => resolve())
      })
    },
  }
}

/** A `POST /command-api` body answered with a JSON-RPC envelope echoing the request id. */
export function eapiReplyBody(result: readonly unknown[], id: string | number): string {
  return JSON.stringify({ jsonrpc: '2.0', result, id })
}

/** The default responder for a healthy device: one empty command result per command sent. */
export function healthyDevice(resultFor?: (commands: readonly unknown[]) => unknown[]): LoopbackResponder {
  return (request, index) => {
    const payload = JSON.parse(request.body) as { id?: string | number; params?: { cmds?: unknown[] } }
    const commands = payload.params?.cmds ?? []
    const results = (resultFor ?? ((cmds: readonly unknown[]) => cmds.map(() => ({}))))(commands)
    void index
    return {
      status: 200,
      headers: { 'content-type': 'application/json' },
      body: eapiReplyBody(results as never, payload.id ?? 1),
    }
  }
}

export interface LoopbackSocketDevice extends Omit<LoopbackDevice, 'scheme' | 'host' | 'port' | 'origin'> {
  /** The socket file the listener is answering on, for the transport's `socketPath` option. */
  readonly socketPath: string
  /** `unix:/tmp/…/eapi.sock` — the address a unix transport reports (pyeapi `SocketConnection.__str__`). */
  readonly address: string
}

/**
 * Unix-socket loopback listener (pyeapi `socket`): an ordinary cleartext `POST /command-api` over an
 * `AF_UNIX` socket. The path lives in the caller's temp directory and is unlinked by `close()`; EOS's
 * own listener is `/var/run/command-api.sock`, which this suite never touches.
 */
export async function listenUnix(socketPath: string, responder: LoopbackResponder): Promise<LoopbackSocketDevice> {
  const server = createHttpServer()
  const requests: LoopbackRequest[] = []
  handleRequest(server, responder, requests, false)
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject)
    server.listen(socketPath, () => resolve())
  })
  return {
    socketPath,
    address: `unix:${socketPath}`,
    requests: () => requests,
    callCount: () => requests.length,
    last: () => requests.at(-1),
    close(): Promise<void> {
      return new Promise((resolve) => {
        server.closeAllConnections()
        server.close(() => {
          try {
            unlinkSync(socketPath)
          } catch {
            // already gone — a closed listener is a removed listener, which is the goal
          }
          resolve()
        })
      })
    },
  }
}
